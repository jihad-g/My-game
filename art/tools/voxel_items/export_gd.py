"""
export_gd.py — writes all items as GDScript data (voxel_item_data.gd).

The game never loads model or texture files: voxel_items.gd reads this
data and builds the meshes in code at runtime.

Format per item: grid size, anchor (pivot) and the voxels as run-length
pairs (count, palette index), base64 encoded. Order: x fastest, then y, then z.
"""
import base64
import numpy as np
from voxkit import PAL


def rle_bytes(flat):
    out = bytearray()
    i, n = 0, len(flat)
    while i < n:
        c = int(flat[i])
        j = i + 1
        while j < n and flat[j] == c and j - i < 255:
            j += 1
        out += bytes((j - i, c))
        i = j
    return bytes(out)


def export_all(item_fns, path):
    lines = []
    lines.append("# AUTO-GENERATED by designer/build.py — do not edit by hand.")
    lines.append("# To change an item: edit art/tools/voxel_items/shard_items.py, then run build.py there.")
    lines.append("# Held item voxel data (Milestone 39). VoxelItems (src/art/voxel_items.gd) builds the meshes.")
    lines.append("class_name VoxelItemData")
    lines.append("extends RefCounted")
    lines.append("")
    lines.append("## Colours in sRGB, index 0 = empty.")
    lines.append("static func palette() -> Array:")
    cols = []
    for (r, g, b) in PAL.rgb:
        cols.append("Color(%.4f, %.4f, %.4f)" % (r / 255.0, g / 255.0, b / 255.0))
    lines.append("\treturn [")
    for k in range(0, len(cols), 4):
        lines.append("\t\t" + ", ".join(cols[k:k + 4]) + ",")
    lines.append("\t]")
    lines.append("")
    lines.append("## 1 = this colour glows (fire, magic).")
    lines.append("static func emissive() -> Array:")
    em = ["1" if e else "0" for e in PAL.emissive]
    lines.append("\treturn [" + ", ".join(em) + "]")
    lines.append("")
    lines.append("## 1 = metal (tinted by the weapon's metal), 2 = accent (tinted by the icon colour).")
    lines.append("static func tint_groups() -> Array:")
    lines.append("\treturn [" + ", ".join(str(t) for t in PAL.tint) + "]")
    lines.append("")
    lines.append("## Palette colour names (for debugging).")
    lines.append("static func colour_names() -> Array:")
    lines.append("\treturn [" + ", ".join('"%s"' % n for n in PAL.names) + "]")
    lines.append("")
    lines.append("## kind: \"hand\" (pivot = grip) or \"prop\" (pivot = bottom centre).")
    lines.append("## size and anchor are in voxels, with z = up (converted to Godot Y-up in VoxelItems).")
    lines.append("## voxel_size = metres per voxel in the game.")
    lines.append("static func items() -> Dictionary:")
    lines.append("\treturn {")
    total = 0
    for fn in item_fns:
        v = fn()
        v.bake(seed=sum(map(ord, v.name)))
        sx, sy, sz = v.g.shape
        flat = v.g.flatten(order="F")
        data = base64.b64encode(rle_bytes(flat)).decode("ascii")
        total += len(data)
        ax, ay, az = v.anchor
        lines.append('\t\t"%s": {' % v.name)
        lines.append('\t\t\t"label": "%s",' % v.label)
        lines.append('\t\t\t"kind": "%s",' % v.kind)
        lines.append("\t\t\t\"size\": Vector3i(%d, %d, %d)," % (sx, sy, sz))
        lines.append("\t\t\t\"anchor\": Vector3(%.2f, %.2f, %.2f)," % (ax, ay, az))
        lines.append('\t\t\t"voxel_size": %.6f,' % v.meters)
        lines.append('\t\t\t"voxels": %d,' % int((v.g > 0).sum()))
        lines.append('\t\t\t"rle": "%s",' % data)
        lines.append("\t\t},")
    lines.append("\t}")
    lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {path}  ({len(item_fns)} items, {total / 1024:.1f} KB of voxel data)")


def decode_check(path_items):
    """Round-trip check used by build.py: decode RLE back and compare."""
    ok = True
    for fn in path_items:
        v = fn()
        v.bake(seed=sum(map(ord, v.name)))
        flat = v.g.flatten(order="F")
        raw = rle_bytes(flat)
        dec = []
        for i in range(0, len(raw), 2):
            dec += [raw[i + 1]] * raw[i]
        if not np.array_equal(np.array(dec, np.uint8), flat):
            print("RLE mismatch:", v.name)
            ok = False
    return ok
